//! The box tree: what box generation produces and layout fills in (`SPEC.md` §5).
//!
//! A [`LayoutBox`] is deliberately thin — a kind, a tag (for the dump and for diagnostics), the
//! computed style it was generated from, geometry, and children. Everything a later phase needs
//! to paint is reachable from here: geometry from [`LayoutBox::rect`], colours from
//! [`LayoutBox::style`], glyphs from text boxes.

use super::Rect;
use crate::css::ComputedStyle;

/// What kind of box this is (`SPEC.md` §5.1–§5.6).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    /// A block-level box generated by `display: block`.
    Block,
    /// An anonymous block created to hold a run of inline content between block siblings
    /// (`SPEC.md` §5.3).
    AnonBlock,
    /// An inline-level box generated by `display: inline`.
    Inline,
    /// A run of text. Always inline-level.
    Text,
    /// A replaced inline box: `<img>` in M1, sized intrinsically or from `width`/`height`
    /// (`SPEC.md` §5.6).
    Atomic,
    /// A forced line break: `<br>` (`SPEC.md` §5.5).
    Break,
}

/// One box in the tree.
#[derive(Debug, Clone, PartialEq)]
pub struct LayoutBox {
    /// Box kind, which decides how layout treats it.
    pub kind: Kind,
    /// Element name, `#anon` for an anonymous block, `#text` for a text run.
    pub tag: String,
    /// Class names from the element, for the dump only (`SPEC.md` §8.1).
    pub classes: Vec<String>,
    /// The computed style this box was generated from.
    pub style: ComputedStyle,
    /// Geometry after layout. For blocks this is the border box; for inline boxes and text runs
    /// it is the fragment they occupy (`SPEC.md` §6.5).
    pub rect: Rect,
    /// Collapsed text content, for text boxes only.
    pub text: Option<String>,
    /// Child boxes in document order.
    pub children: Vec<LayoutBox>,
}

impl LayoutBox {
    /// Create an empty box of `kind`.
    pub fn new(kind: Kind, tag: &str, style: ComputedStyle) -> LayoutBox {
        LayoutBox {
            kind,
            tag: tag.to_string(),
            classes: Vec::new(),
            style,
            rect: Rect::default(),
            text: None,
            children: Vec::new(),
        }
    }

    /// Whether this box participates in an inline formatting context (`SPEC.md` §5.4).
    pub fn is_inline_level(&self) -> bool {
        matches!(
            self.kind,
            Kind::Inline | Kind::Text | Kind::Atomic | Kind::Break
        )
    }

    /// Whether this box is block-level.
    pub fn is_block_level(&self) -> bool {
        matches!(self.kind, Kind::Block | Kind::AnonBlock)
    }

    /// The label used by the tree dump: element name plus classes, or the quoted text.
    pub fn label(&self) -> String {
        match (&self.kind, &self.text) {
            (Kind::Text, Some(text)) => format!("\"{}\"", escape(text)),
            _ if self.tag == "#anon" => "#anon".to_string(),
            _ => {
                let mut label = self.tag.clone();
                for class in &self.classes {
                    label.push('.');
                    label.push_str(class);
                }
                label
            }
        }
    }
}

/// A whole laid-out document.
#[derive(Debug, Clone, PartialEq)]
pub struct BoxTree {
    /// The root box, always the `html` element's box.
    pub root: LayoutBox,
    /// Canvas width in pixels.
    pub width: u32,
    /// Canvas height in pixels.
    pub height: u32,
    /// `<title>` text, printed in the dump header (`SPEC.md` §8.1).
    pub title: Option<String>,
}

/// Escape control characters so a text run occupies exactly one dump line.
pub fn escape(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for ch in text.chars() {
        match ch {
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '"' => out.push_str("\\\""),
            _ => out.push(ch),
        }
    }
    out
}
