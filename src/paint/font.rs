#[cfg(test)]
mod tests {
    use super::*;

    /// The table covers every printable ASCII code point exactly once.
    #[test]
    fn table_covers_printable_ascii() {
        assert_eq!(GLYPHS.len(), GLYPH_COUNT);
        assert!(glyph(' ').is_some());
        assert!(glyph('~').is_some());
        assert!(glyph('\u{7f}').is_none());
        assert!(glyph('\u{00e9}').is_none());
    }

    /// A space is blank and a letter has ink, so a font that silently lost its data fails here
    /// rather than producing a blank page nobody can explain.
    #[test]
    fn space_is_blank_and_letters_have_ink() {
        assert!(glyph(' ').unwrap().iter().all(|row| *row == 0));
        assert!(glyph('H').unwrap().iter().any(|row| *row != 0));
        assert!(glyph('a').unwrap().iter().any(|row| *row != 0));
    }
}
