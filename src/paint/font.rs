//! The built-in 8×16 bitmap font (`SPEC.md` §6.6).
//!
//! # Provenance
//!
//! All 95 printable ASCII glyphs (U+0020–U+007E) were hand-drawn for this project on a 5×7
//! grid, then expanded to the 8×16 cell the specification requires by nearest-neighbour column
//! repetition and doubling each row, with one blank row at the top and bottom. They are not
//! copied from a VGA ROM or any other bitmap font: the 5×7 source is this project's own drawing,
//! and the expansion is deterministic. The font therefore carries the repository's own
//! `MIT OR Apache-2.0` licence and the zero-dependency rule stays intact (`SPEC.md` §1.2).
//!
//! Row 0 is the top of the cell and bit 7 is the leftmost pixel. Characters outside the
//! printable range render blank, which is a visible fallback rather than a panic.

/// Width of one glyph cell in the native bitmap.
pub const GLYPH_WIDTH: usize = 8;

/// Height of one glyph cell in the native bitmap.
pub const GLYPH_HEIGHT: usize = 16;

/// First code point in the table: space.
pub const FIRST_CHAR: u8 = 0x20;

/// Number of glyphs in the table: every printable ASCII character.
pub const GLYPH_COUNT: usize = 95;

/// The glyph mask for `ch`, or `None` when it is outside printable ASCII.
///
/// # Examples
///
/// ```
/// use swiftrender::paint::font::{glyph, GLYPH_HEIGHT};
/// let h = glyph('H').expect("H is printable ASCII");
/// assert_eq!(h.len(), GLYPH_HEIGHT);
/// assert!(h.iter().any(|row| *row != 0), "H has ink");
/// assert!(glyph('\u{00e9}').is_none(), "non-ASCII renders blank");
/// ```
pub fn glyph(ch: char) -> Option<&'static [u8; GLYPH_HEIGHT]> {
    let code = ch as u32;
    if !(u32::from(FIRST_CHAR)..=0x7e).contains(&code) {
        return None;
    }
    GLYPHS.get(code as usize - usize::from(FIRST_CHAR))
}

